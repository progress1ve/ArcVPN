"""Verified cabinet instructions and recurring cases from support history."""

import re

from bot.services.support_client_docs import identify_client


PRODUCT_FACTS = """Сверенные факты кабинета ArcVPN:
• Первое подключение: «Подключить VPN» → устройство → Happ или INCY → установить приложение.
  Happ открывается кнопкой импорта; для INCY кабинет копирует ссылку, затем в INCY добавляют подписку из буфера.
  После импорта выберите «Автовыбор». Полную ссылку в чат присылать нельзя.
  Отдельное приложение ArcVPN искать в магазине не нужно. Не предлагайте удалить профиль или переустановить клиент первым шагом.
  Автовыбор и обычные локации используют основной трафик. Количество устройств и ГБ обхода можно увеличить в кабинете.
• Основной трафик безлимитный. У «Обхода глушилок» отдельный запас ГБ; объём зависит от конкретного тарифа.
  Докупленный пакет обхода действует один календарный месяц с момента начисления, независимо от обновления основного лимита.
  «0 — бесконечность» в клиенте само по себе ничего не говорит о запасе ГБ обхода: сверяйтесь с кабинетом.
  Не определяйте конкретный тариф или баланс по названию профиля и не обещайте компенсаций.
• «Настройки → Устройства» показывает зарегистрированные устройства и лимит.
  «Настройки → Автопродление» показывает состояние автопродления и позволяет отключить его. Отключение не сокращает текущий срок.
• Если VPN включается, но трафик нигде не проходит, отличайте это от ошибки подключения.
  Если остальные сайты работают, уточняйте сообщение об ошибке конкретного сервиса. Используйте уже названный сервис и клиент,
  учитывайте ранее пройденные шаги, не выдумывайте причину блокировки, локации и пути меню VPN-клиента.
• Для вопросов о списании, конкретной покупке, пропавших ГБ, сбросе, текущем тарифе и индивидуальных условиях нужна сверка менеджером.
  Если платёж уже прошёл, не предлагайте платить повторно.
"""


def known_reply(messages, reason):
    """Return a verified response and optional handoff reason for a known case."""
    latest = messages[-1]["body"].strip().lower()
    if reason in {"requested", "account", "diagnosis"}:
        return None

    if reason in {None, "payment"} and re.fullmatch(
        r"(?:здравствуйте[.!]?\s*)?(?:хочу уточнить[,:]?\s*)?"
        r"(?:плат[её]ж автоматически ид[её]т или мне продлить самостоятельно|"
        r"(?:как (?:проверить|отключить)|где (?:проверить|отключить|посмотреть)) автопродление|"
        r"автопродление включено\s*или\s*нет)[?!.]*",
        latest,
    ):
        return (
            "Откройте «Настройки → Автопродление» в кабинете. Там видно, включены ли автоматические списания. "
            "Если хотите отключить их, нажмите «Отключить и отвязать способ оплаты» и подтвердите. "
            "Текущая подписка продолжит действовать до даты окончания.",
            None,
        )

    if reason == "payment":
        return None
    # A short clarification can follow an incorrect reply to a pasted app error.
    error_pattern = r"geosite\.dat|критическая ошибка\s+xray\s*core|ядро не может быть запущено"
    error = latest if re.search(error_pattern, latest) else ""
    if not error and re.fullmatch(r"(?:это (?:выходит|пишет|появляется) в (?:приложении\s*)?)?[«“\"]?(?:happ|incy|хапп|инси)[»”\"]?[.!]?", latest):
        previous = next((row["body"].lower() for row in reversed(messages[:-1]) if row["sender"] == "user"), "")
        if re.search(error_pattern, previous):
            error = previous
    if error:
        if "geosite.dat" not in error:
            return (
                "Ошибка возникает при запуске ядра VPN-приложения. Пришлите точный текст ошибки и название клиента, "
                "если вы его ещё не указали. Ссылку подписки и ключи присылать не нужно.",
                None,
            )
        client = identify_client(messages)
        if error == latest and "без маршрутизирующего профиля" in error and "запуск" in error:
            return "Для временного подключения нажмите «Запуск» в этом окне. Правила профиля применяться не будут. Если важно сохранить маршрутизацию, оставьте профиль включённым и нажмите «Позвать менеджера».", None
        if client == "happ":
            return "Обновите Happ, если доступна новая версия, и снова включите VPN. Если приложение уже обновлено и подключение не удаётся, нажмите «Позвать менеджера».", None
        if client == "incy":
            return "В INCY откройте активный профиль маршрутизации, обновите его геофайлы вручную и снова включите VPN.", None
        return "В Happ проверьте обновление приложения. В INCY откройте активный профиль маршрутизации и обновите его геофайлы. Затем снова включите VPN.", None

    if not reason and re.search(r"не помогло|та же ошибка|ошибка осталась|ничего не работает", latest) and any(
        row["sender"] == "user" and "geosite.dat" in row["body"].lower() for row in messages[:-1]
    ):
        return "Передали менеджеру результат проверки. Он ответит здесь, повторять шаг не нужно.", "diagnosis"

    if not reason and re.search(r"\bxray\s*core\b", latest):
        return "Пришлите точный текст ошибки XrayCore. Если название VPN-приложения ещё не указано, добавьте его. Ссылка подписки не нужна.", None

    if reason:
        return None

    if re.search(r"0\s*[—–-]\s*бесконечност", latest):
        return (
            "По надписи «0 — бесконечность» в VPN-приложении нельзя определить остаток ГБ обхода. "
            "Посмотрите лимит обхода на главном экране кабинета. Если лимит там тоже выглядит неверно, напишите об этом здесь.",
            None,
        )
    if re.search(r"(?:остальные|другие) (?:сайты|сервисы|приложения)\s+(?:нормально\s+)?(?:работают|открываются)", latest) and not re.search(r"телеграм|telegram|\bтг\b", latest):
        return (
            "Раз другие сайты и приложения работают, проверим сбой отдельно. Попробуйте открыть проблемный сервис "
            "через одну другую обычную локацию. Если ошибка сохранится, напишите её точный текст или сообщите, что на другой локации ошибка та же.",
            None,
        )
    if re.search(r"подключ[её]н|впн включ[её]н|vpn включ[её]н", latest) and re.search(
        r"ни один сайт|ничего не (?:работает|открывается)|ни одно приложение|(?:все|любые) сайты не", latest
    ) and re.search(r"авто\s*выбор", latest):
        return (
            "VPN показывает подключение, но сайты не открываются. Выберите в VPN-приложении одну обычную локацию вручную "
            "и откройте любой сайт. Напишите, загрузился ли он. Если вы уже пробовали другую локацию, напишите результат этой проверки.",
            None,
        )
    return None
