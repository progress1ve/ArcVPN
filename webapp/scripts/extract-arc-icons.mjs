import { readFileSync, writeFileSync } from 'node:fs'

const collection = JSON.parse(
  readFileSync(new URL('../node_modules/@iconify-json/fluent/icons.json', import.meta.url), 'utf8'),
)

const selected = {
  home: 'home-24-regular',
  homeActive: 'home-24-filled',
  gift: 'gift-24-regular',
  giftActive: 'gift-24-filled',
  headset: 'headset-24-regular',
  headsetActive: 'headset-24-filled',
  settings: 'settings-24-regular',
  settingsActive: 'settings-24-filled',
  wallet: 'wallet-24-regular',
  download: 'arrow-download-24-regular',
  phone: 'phone-24-regular',
  pulse: 'pulse-24-regular',
  signal: 'wifi-4-24-regular',
  lte: 'cellular-data-4-24-regular',
  arrow: 'arrow-right-24-regular',
  external: 'arrow-up-right-24-regular',
  back: 'arrow-left-24-regular',
  close: 'dismiss-24-regular',
  copy: 'copy-24-regular',
  chat: 'chat-24-regular',
  question: 'question-circle-24-regular',
  email: 'mail-24-regular',
  telegram: 'send-24-filled',
  logout: 'sign-out-24-regular',
  bell: 'alert-24-regular',
  monitor: 'desktop-24-regular',
  link: 'link-24-regular',
  shield: 'shield-checkmark-24-regular',
  caret: 'chevron-right-24-regular',
  users: 'people-24-regular',
  send: 'send-24-regular',
  check: 'checkmark-circle-24-regular',
  calendar: 'calendar-24-regular',
  devices: 'phone-desktop-24-regular',
  file: 'document-text-24-regular',
  card: 'payment-24-regular',
  lock: 'lock-closed-24-regular',
  identity: 'person-24-regular',
}

const icons = Object.fromEntries(
  Object.entries(selected).map(([alias, name]) => {
    const icon = collection.icons[name]
    if (!icon) throw new Error(`Fluent icon not found: ${name}`)
    return [alias, icon]
  }),
)

const output = `// Generated by scripts/extract-arc-icons.mjs.\nexport default ${JSON.stringify(icons, null, 2)}\n`
writeFileSync(new URL('../src/lib/arc-icons.js', import.meta.url), output)
